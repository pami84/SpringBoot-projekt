package ECutbildning.SpringBoot_projekt;

public class Calculator {

    public int add(int a, int b) {
        return a + b;
    }

    public int negativeAdd(int a, int b){
        return a+ b;
    }
    public int subtract(int a, int b){
        return a - b;
    }
    public int negativeSubtract(int a, int b){
        return a - b;
    }
    public int multiply(int a, int b){
        return a * b;
    }

    public int negativeMultiply(int a, int b){
        return a * b;
    }
    public int divide(int a, int b){
        return a / b;
    }

    public int negativeDivide(int a, int b){
        return a / b;
    }
    public double divideWithDecimals(double a, double b){
        return a / b;
    }
}

